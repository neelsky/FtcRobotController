@TeleOp(name = "Event Code", group = "Glitch")
public class EventCode extends LinearOpMode {

    Servo indicator;
    private DcMotor frontLeftMotor;
    private DcMotor backLeftMotor;
    private DcMotor frontRightMotor;
    private DcMotor backRightMotor;

    private DcMotorEx intake;


    @Override
    public void runOpMode() throws InterruptedException {
        initializeMotors();

        waitForStart();



        while (opModeIsActive()) {

            doDriving();
            RunIntakemotor();
            runlight();

            telemetry.update();
        }


    }


    private void doDriving() {
        double y = -gamepad1.left_stick_y;
        double x = gamepad1.left_stick_x * 1.1;
        double rx = gamepad1.right_stick_x;


        double denominator = Math.max(Math.abs(y) + Math.abs(x) + Math.abs(rx), 1);
        frontLeftMotor.setPower((y + x + rx) / denominator);
        backLeftMotor.setPower((y - x + rx) / denominator);
        frontRightMotor.setPower((y - x - rx) / denominator);
        backRightMotor.setPower((y + x - rx) / denominator);
    }




    private void RunIntakemotor() {
        if (gamepad1.dpad_up) {
            intake.setPower(0.5);
        }
        if (gamepad1.dpad_down) {
            intake.setPower(-0.5);
        }

        if (gamepad1.left_bumper){
            intake.setPower(0);
        }
    }
    private void runlight(){
        indicator.setPosition(0.5);
    }



    private void initializeMotors() {
        indicator = hardwareMap.get(Servo.class, "indicator");
        frontLeftMotor = hardwareMap.dcMotor.get("frontLeft");
        backLeftMotor = hardwareMap.dcMotor.get("backLeft");
        frontRightMotor = hardwareMap.dcMotor.get("frontRight");
        backRightMotor = hardwareMap.dcMotor.get("backRight");
        intake = hardwareMap.get(DcMotorEx.class, "intake");

        frontLeftMotor.setDirection(DcMotor.Direction.REVERSE);
        backLeftMotor.setDirection(DcMotor.Direction.REVERSE);
        frontRightMotor.setDirection(DcMotor.Direction.FORWARD);
        backRightMotor.setDirection(DcMotor.Direction.FORWARD);


        frontLeftMotor.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);
        backLeftMotor.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);
        frontRightMotor.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);
        backRightMotor.setZeroPowerBehavior(DcMotor.ZeroPowerBehavior.BRAKE);

    }
}